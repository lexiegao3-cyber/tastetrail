import { writeFileSync } from "node:fs";
import { openDatabase } from "../db/index.js";
import {
  blend, contentScores, evaluate, itemCfScores, popularityModel, scoredModel, temporalSplit,
  type ItemFeatures, type Metrics, type Rating,
} from "./offline.js";

/**
 *   npm run eval -- [--users 2000] [--k 10] [--out ../docs/EVAL.md]
 * Reads imported Food.com ratings and recipe features from the database.
 */
const args = process.argv.slice(2);
const opt = (k: string, d: string) => {
  const i = args.indexOf(`--${k}`);
  return i >= 0 ? args[i + 1]! : d;
};
const k = Number(opt("k", "10"));
const maxUsers = Number(opt("users", "2000"));

const db = await openDatabase({ url: process.env.DATABASE_URL, dataDir: process.env.PLATEWISE_DATA_DIR ?? "./pgdata" });
const t0 = Date.now();
const ratings = await db.query<Rating>(
  `SELECT user_key AS user, recipe_id AS item, rating::int AS rating, to_char(rated_on, 'YYYY-MM-DD') AS date
     FROM external_ratings WHERE source = 'food.com' AND rated_on IS NOT NULL`,
);
const featRows = await db.query<{ id: string; cuisine: string; tags: string[]; foods: string[] }>(
  `SELECT r.id, r.cuisine, r.tags, coalesce(array_agg(ri.food_id) FILTER (WHERE ri.food_id IS NOT NULL), '{}') AS foods
     FROM recipes r LEFT JOIN recipe_ingredients ri ON ri.recipe_id = r.id
    WHERE r.source = 'food.com' GROUP BY r.id`,
);
await db.close();
if (!ratings.length) {
  console.error("No Food.com ratings in the database. Run npm run etl:foodcom first.");
  process.exit(1);
}
const features = new Map<string, ItemFeatures>(featRows.map((r) => [r.id, { cuisine: r.cuisine, tags: r.tags, foods: r.foods }]));

const split = temporalSplit(ratings, { maxUsers });
const pop = popularityModel(split.train);
const cf = itemCfScores(split.train);
const content = contentScores(features);
const models = [
  pop,
  scoredModel("Item-item CF", cf, pop),
  scoredModel("Content (TF-IDF familiarity)", content, pop),
  scoredModel("Hybrid: CF + content", blend(cf, content), pop),
];
const catalog = new Set(split.train.map((r) => r.item)).size;
const results: Metrics[] = models.map((m) => {
  const t = Date.now();
  const r = evaluate(m, split, k, catalog);
  console.error(`${m.name}: ${((Date.now() - t) / 1000).toFixed(1)} s`);
  return r;
});
const seconds = Math.round((Date.now() - t0) / 1000);

const fmt = (x: number) => x.toFixed(4);
const table = [
  `| Model | Precision@${k} | Recall@${k} | NDCG@${k} | Hit rate@${k} | Catalog coverage |`,
  "| --- | --- | --- | --- | --- | --- |",
  ...results.map((r) => `| ${r.model} | ${fmt(r.precision)} | ${fmt(r.recall)} | ${fmt(r.ndcg)} | ${fmt(r.hitRate)} | ${(r.coverage * 100).toFixed(2)}% |`),
].join("\n");
const summary = {
  ratings: ratings.length, recipes: features.size, trainRatings: split.train.length, cutoff: split.cutoff,
  testUsers: split.testUsers.length, catalog, k, seconds, results,
};
console.log(JSON.stringify(summary, null, 2));
console.log("\n" + table);

const out = opt("out", "");
if (out) {
  writeFileSync(out, `# Offline evaluation

Generated by \`npm run eval\` on ${new Date().toISOString().slice(0, 10)}.

- Data: ${ratings.length.toLocaleString("en-US")} Food.com ratings over ${features.size.toLocaleString("en-US")} imported recipes.
- Split: global time cutoff at ${split.cutoff}; ${split.train.length.toLocaleString("en-US")} earlier ratings train every model.
- Test users: ${split.testUsers.length.toLocaleString("en-US")} (seeded sample) with at least 3 liked recipes (rating ≥ 4) before the cutoff and at least one after it.
- Relevant items: recipes a test user rated ≥ 4 after the cutoff that existed before it. ${catalog.toLocaleString("en-US")} recipes are recommendable.
- Each model excludes recipes the user already rated before the cutoff.

${table}

Popularity = most-liked recipes before the cutoff. Item-item CF = the app's co-like cosine, best match over the user's 50 most recent likes. Content = the engine's TF-IDF familiarity over cuisine, tags and ingredients. Hybrid = equal-weight blend of the two, as in the engine's weights. Models fall back to popularity when they have fewer than ${k} candidates.

What this does not measure: the taste, nutrition, convenience and price factors need user preferences, a pantry and meal targets, which Food.com does not have.
`);
  console.log(`wrote ${out}`);
}
